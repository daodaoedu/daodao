// ---------------------------------------------------------------- main

const args = process.argv.slice(2)
const checkOnly = args.includes('--check')
const onlyIdx = args.indexOf('--only')
const only = onlyIdx !== -1 ? args[onlyIdx + 1] : null

const hash = (s: string) => createHash('sha256').update(s).digest('hex')

let drift = 0
let written = 0

const jobs: { id: string; label: string; target: string; files: OutFile[] }[] = []

for (const [id, platform] of Object.entries(manifest.platforms)) {
  if (only && only !== id) continue
  if (platform.emit === 'native') continue
  const files =
    platform.emit === 'full-copy'
      ? buildAgentsSkills(platform)
      : platform.emit === 'openai-plugin'
        ? buildOpenAiPlugin(platform)
        : buildClaudeAi(platform)
  jobs.push({ id, label: platform.label, target: platform.target, files })
}

if (!only || only === 'codex-hooks') jobs.push({ id: 'codex-hooks', label: 'Codex hooks', target: '.codex/', files: buildCodexHooks() })
if (!only || only === 'openai-plugin') jobs.push({ id: 'repo-marketplace', label: 'Repo marketplace', target: '.agents/plugins/', files: buildRepoMarketplace() })

if (errors.length) {
  console.error('✗ canonical 有問題，先修好再產出：\n')
  for (const e of errors) console.error(`  - ${e}`)
  process.exit(1)
}

/**
 * 產出前會整個刪掉 target 目錄。platforms.json 是手改的，target 打錯一個字就可能
 * 刪掉 canonical（例如把 claude-code 的 emit 從 native 改掉，target 是 `plugin/`，
 * 整個 plugin/skills 就沒了）。刪除前一律先過這關。
 */
function assertSafeToWipe(target: string) {
  const abs = resolve(REPO_ROOT, target)
  const rel = relative(REPO_ROOT, abs)

  if (rel === '' || rel.startsWith('..')) {
    throw new Error(`拒絕刪除「${target}」：不在 repo 內，或就是 repo 根目錄`)
  }
  // canonical 的來源目錄一律不可當作產出目標
  const protectedRoots = ['plugin/skills', 'plugin/hooks', 'plugin/templates', 'plugin/docs', 'plugin/scripts', '.claude-plugin', '.git']
  for (const guarded of protectedRoots) {
    const guardedAbs = resolve(REPO_ROOT, guarded)
    if (abs === guardedAbs || guardedAbs.startsWith(`${abs}/`) || abs.startsWith(`${guardedAbs}/`)) {
      throw new Error(`拒絕刪除「${target}」：會波及 canonical 來源 ${guarded}`)
    }
  }
}

for (const job of jobs) {
  const targetAbs = resolve(REPO_ROOT, job.target)
  if (!checkOnly && job.id !== 'codex-hooks' && job.id !== 'repo-marketplace' && existsSync(targetAbs)) {
    assertSafeToWipe(job.target)
    rmSync(targetAbs, { recursive: true, force: true })
  }
  for (const f of job.files) {
    const abs = resolve(REPO_ROOT, f.path)
    if (checkOnly) {
      const current = existsSync(abs) ? readFileSync(abs, 'utf8') : null
      if (current === null || hash(current) !== hash(f.content)) {
        console.error(`✗ 產物過期：${f.path}`)
        drift++
      }
      continue
    }
    mkdirSync(dirname(abs), { recursive: true })
    writeFileSync(abs, f.content)
    written++
  }
  if (!checkOnly) console.log(`✓ ${job.label} → ${job.target}（${job.files.length} 檔）`)
}

if (checkOnly) {
  if (drift > 0) {
    console.error(`\n${drift} 個產物與 plugin/skills/ 不同步。跑 \`pnpm plugin:build\` 後重新 commit。`)
    process.exit(1)
  }
  console.log('✓ 所有平台產物與 canonical 同步')
} else {
  console.log(`\n完成，共寫入 ${written} 個檔案。`)
}
