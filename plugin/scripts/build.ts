function buildCodexHooks(): OutFile[] {
  const claudeHooks = JSON.parse(readFileSync(join(PLUGIN_ROOT, 'hooks', 'hooks.json'), 'utf8')).hooks
  // Codex 的 hook command 以 session cwd 執行，且文件明講不要用相對路徑（Codex 可能從別的目錄啟動）。
  // $REPO_ROOT 只在 skills 探索有定義，hook command 沒有；官方示範用的是 git rev-parse。
  const root = '$(git rev-parse --show-toplevel)/plugin'
  const rewrite = (s: string) => {
    const expanded = s.replaceAll('${CLAUDE_PLUGIN_ROOT}', root)
    // Claude Code 直接執行腳本路徑；Codex 的示範一律帶 interpreter，這裡補上並加引號
    return /^\$\(git rev-parse[^"]*\.sh$/.test(expanded) ? `bash "${expanded}"` : expanded
  }
  const out: Record<string, unknown> = {}
  for (const [event, groups] of Object.entries(claudeHooks as Record<string, any[]>)) {
    out[event] = groups.map((g) => ({
      ...(g.matcher ? { matcher: g.matcher } : {}),
      hooks: g.hooks.map((h: any) => ({ ...h, command: rewrite(h.command) })),
    }))
  }
  return [
    {
      path: '.codex/hooks.json',
      content: `${JSON.stringify({ $comment: BANNER.replace(/<!--|-->/g, '').trim(), hooks: out }, null, 2)}\n`,
    },
    {
      path: '.codex/README.md',
      content: [
        '# Codex 設定',
        '',
        BANNER,
        '',
        '`hooks.json` 與 Claude Code 的 `plugin/hooks/hooks.json` 指向同一批腳本，事件名相同，',
        '所以 pre-pr-gate、stop-quality-gate 等閘門在 Codex 也會實際觸發。',
        '',
        '**第一次使用要先信任**：在 Codex 跑 `/hooks` 檢視並信任這份設定（會對內容做 hash pinning）。',
        '沒信任之前 hooks 不會執行——那就等同沒有閘門，此時 agent 必須自己逐項跑同一批腳本並貼出輸出。',
        '',
        'skills 不在這裡：Codex 掃的是 `.agents/skills/`（見該目錄 README）。',
        '舊版 `.codex/skills/` 不是 Codex 的實際載入路徑，已於 2026-09-21 移除。',
        '',
      ].join('\n'),
    },
  ]
}

